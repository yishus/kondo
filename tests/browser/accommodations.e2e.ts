import { expect, test } from "@playwright/test";
import { ensureSignedIn } from "./auth";

test("shortlist stays, compare dates, confirm a booking, and manage its PDF", async ({ page }, testInfo) => {
  await ensureSignedIn(page);
  await page.getByLabel("Add a new trip").fill(`Accommodations ${Date.now()}`);
  await page.getByRole("button", { name: "Add trip", exact: true }).click();
  await page.waitForURL(/\/trips\//);
  const tripUrl = page.url();
  for (const date of ["2026-10-01", "2026-10-02", "2026-10-05", "2026-10-06"]) {
    await page.locator("#trip-date").fill(date);
    await page.getByRole("button", { name: "Add day", exact: true }).click();
    await expect(page.locator("#trip-date")).toHaveValue("");
  }
  await page.getByRole("link", { name: "Accommodations", exact: true }).click();
  await page.getByLabel("City / area / region", { exact: true }).fill("Tokyo");
  await page.getByRole("button", { name: "Add place", exact: true }).click();
  const tokyo = page.getByRole("region", { name: "Accommodations in Tokyo", exact: true });
  await tokyo.getByRole("button", { name: "Add accommodation" }).click();
  const dialog = page.getByRole("dialog");
  await dialog.getByLabel("Accommodation name").fill("Tokyo Hotel");
  await page.route("**/places?*", (route) => route.fulfill({ json: { places: [{ id: "ChIJ_hotel", name: "Tokyo Hotel", address: "1 Tokyo Street, Tokyo", attributions: [] }], error: null } }));
  await dialog.getByLabel("Search for a place").fill("1 Tokyo Street");
  await dialog.getByRole("button", { name: "Search", exact: true }).click();
  await dialog.getByRole("button", { name: /Tokyo Hotel.*1 Tokyo Street/ }).click();
  await expect(dialog).toContainText("1 Tokyo Street, Tokyo");
  await dialog.getByRole("button", { name: "Add date option" }).click();
  const first = dialog.getByRole("group", { name: /^Option 1/ });
  await first.getByLabel("Check-in", { exact: true }).fill("2026-10-01");
  await first.getByLabel("Check-out", { exact: true }).fill("2026-10-04");
  await first.getByLabel("Total cost").fill("450");
  await expect(first).toContainText("3 nights · SGD 150.00 / night");
  await dialog.getByRole("button", { name: "Add date option" }).click();
  const second = dialog.getByRole("group", { name: /^Option 2/ });
  await second.getByLabel("Check-in", { exact: true }).fill("2026-10-02");
  await second.getByLabel("Check-out", { exact: true }).fill("2026-10-06");
  await second.getByLabel("Total cost").fill("520");
  await second.getByLabel("Confirm this stay").check();
  await dialog.getByLabel("Booked via").fill("Booking.com");
  await dialog.getByLabel("Free cancellation", { exact: true }).check();
  await dialog.getByLabel("Free cancellation until").fill("2026-09-29T18:00");
  await dialog.getByLabel("Cancellation time zone").fill("Asia/Tokyo");
  await dialog.getByLabel("Description").fill("Booked by Alex. Two guests.");
  const pdf = Buffer.from("%PDF-1.4\nTest booking\n%%EOF");
  await dialog.getByLabel("Booking confirmation PDF").setInputFiles({ name: "tokyo-booking.pdf", mimeType: "application/pdf", buffer: pdf });
  await dialog.getByRole("button", { name: "Save accommodation" }).click();
  await expect(dialog).toHaveCount(0);
  await expect(tokyo).toContainText("1 candidate · 1 confirmed");
  await expect(tokyo).toContainText("SGD 130.00 / night");
  await page.reload();
  await expect(tokyo).toContainText("Booked by Alex");
  await expect(tokyo).toContainText("Asia/Tokyo");
  await page.screenshot({ path: testInfo.outputPath("accommodations-desktop.png"), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(tokyo.getByRole("button", { name: "Tokyo Hotel", exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath("accommodations-mobile.png"), fullPage: true });
  await page.setViewportSize({ width: 1280, height: 900 });
  const pdfUrl = (await tokyo.getByRole("link", { name: "PDF · tokyo-booking.pdf" }).getAttribute("href"))!;
  expect(await (await page.request.get(pdfUrl)).body()).toEqual(pdf);
  expect((await page.request.get(pdfUrl.replace(/\/trips\/[^/]+\//, "/trips/other/"))).status()).toBe(404);
  await page.getByRole("link", { name: "Itinerary", exact: true }).click();
  const stays = page.getByRole("article", { name: "Confirmed accommodation: Tokyo Hotel", exact: true });
  await expect(stays).toHaveCount(2);
  for (const date of ["Fri, Oct 2", "Mon, Oct 5"]) {
    const day = page.getByRole("region", { name: `Itinerary for ${date}`, exact: true });
    const stay = day.locator("..").getByRole("article", { name: "Confirmed accommodation: Tokyo Hotel", exact: true });
    await expect(stay).toBeVisible();
    await expect(day.getByRole("article")).toHaveCount(0);
    await expect(day.getByLabel("0 cards", { exact: true })).toBeVisible();
    await expect(stay.getByRole("button")).toHaveCount(0);
    expect(await stay.evaluate((element) => element.previousElementSibling?.getAttribute("aria-label"))).toBe(`Itinerary for ${date}`);
    await expect(stay.getByRole("link", { name: "Google Maps" })).toHaveAttribute("href", /query_place_id=ChIJ_hotel/);
  }
  await page.screenshot({ path: testInfo.outputPath("itinerary-confirmed-stays.png"), fullPage: true });
  await stays.first().getByRole("link", { name: "Edit Tokyo Hotel", exact: true }).click();
  await expect(page).toHaveURL(/\/accommodations\?edit=/);
  await expect(page.getByRole("link", { name: "Accommodations", exact: true })).toHaveAttribute("aria-current", "page");
  await expect(dialog.getByLabel("Accommodation name")).toHaveValue("Tokyo Hotel");
  await page.reload();
  await expect(dialog.getByLabel("Accommodation name")).toHaveValue("Tokyo Hotel");
  await expect(dialog.getByLabel("Confirm this stay").nth(1)).toBeChecked();
  const download = page.waitForEvent("download");
  await dialog.getByRole("link", { name: "Download PDF" }).click();
  expect((await download).suggestedFilename()).toBe("tokyo-booking.pdf");
  await dialog.getByLabel("Remove booking PDF").check();
  await dialog.getByRole("button", { name: "Cancel", exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await expect(page).toHaveURL(`${tripUrl}/accommodations`);
  expect((await page.request.get(pdfUrl)).status()).toBe(200);
  await tokyo.getByRole("button", { name: "Tokyo Hotel", exact: true }).click();
  await dialog.getByRole("button", { name: "Mark as unconfirmed" }).click();
  await dialog.getByLabel("Remove booking PDF").check();
  await dialog.getByRole("button", { name: "Save accommodation" }).click();
  await expect(dialog).toHaveCount(0);
  await expect(tokyo).toContainText("1 candidate · 0 confirmed");
  expect((await page.request.get(pdfUrl)).status()).toBe(404);
  await tokyo.getByRole("button", { name: "Add accommodation" }).click();
  await dialog.getByLabel("Accommodation name").fill("Apartment");
  await dialog.getByRole("combobox", { name: "Type", exact: true }).selectOption("airbnb");
  await dialog.getByRole("button", { name: "Save accommodation" }).click();
  await expect(dialog).toHaveCount(0);
  await expect(tokyo).toContainText("2 candidates");
  await tokyo.getByRole("button", { name: "Apartment", exact: true }).click();
  page.once("dialog", (confirmation) => confirmation.accept());
  await dialog.getByRole("button", { name: "Delete accommodation", exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await expect(tokyo).toContainText("1 candidate");
  await tokyo.getByRole("button", { name: "Edit place" }).click();
  await tokyo.getByLabel("City / area / region", { exact: true }).fill("Greater Tokyo");
  await tokyo.getByRole("button", { name: "Save place" }).click();
  const renamed = page.getByRole("region", { name: "Accommodations in Greater Tokyo", exact: true });
  await expect(renamed).toBeVisible();
  await renamed.getByRole("button", { name: "Edit place" }).click();
  page.once("dialog", (confirmation) => confirmation.accept());
  await renamed.getByRole("button", { name: "Delete place" }).click();
  await expect(renamed).toHaveCount(0);
  await page.getByRole("link", { name: "Itinerary", exact: true }).click();
  await expect(page).toHaveURL(tripUrl);
  await expect(page.getByRole("region", { name: "Unscheduled cards" })).toBeVisible();
  await expect(stays).toHaveCount(0);
});

test("invalid dates and fake PDFs are rejected without losing the draft", async ({ page }) => {
  await ensureSignedIn(page);
  await page.getByLabel("Add a new trip").fill(`Stay validation ${Date.now()}`);
  await page.getByRole("button", { name: "Add trip", exact: true }).click();
  await page.waitForURL(/\/trips\//);
  await page.getByRole("link", { name: "Accommodations", exact: true }).click();
  await page.getByLabel("City / area / region", { exact: true }).fill("Kyoto");
  await page.getByRole("button", { name: "Add place", exact: true }).click();
  await page.getByRole("button", { name: "Add accommodation" }).click();
  const dialog = page.getByRole("dialog");
  await dialog.getByLabel("Accommodation name").fill("Ryokan");
  await dialog.getByRole("button", { name: "Add date option" }).click();
  await dialog.getByLabel("Check-in", { exact: true }).fill("2026-10-01");
  await dialog.getByLabel("Check-out", { exact: true }).fill("2026-10-01");
  await dialog.getByLabel("Total cost").fill("100");
  await dialog.getByRole("button", { name: "Save accommodation" }).click();
  await expect(dialog.getByRole("alert")).toContainText("check-out date must be after");
  await dialog.getByLabel("Check-out", { exact: true }).fill("2026-10-02");
  await dialog.getByLabel("Booking confirmation PDF").setInputFiles({ name: "fake.pdf", mimeType: "application/pdf", buffer: Buffer.from("not a PDF") });
  await dialog.getByRole("button", { name: "Save accommodation" }).click();
  await expect(dialog.getByRole("alert")).toContainText("not a valid PDF");
  await expect(dialog.getByLabel("Accommodation name")).toHaveValue("Ryokan");
  await dialog.getByLabel("Booking confirmation PDF").setInputFiles([]);
  await dialog.getByRole("button", { name: "Save accommodation" }).click();
  await expect(dialog).toHaveCount(0);
});
